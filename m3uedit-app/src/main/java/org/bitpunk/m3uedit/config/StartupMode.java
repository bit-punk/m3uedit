package org.bitpunk.m3uedit.config;

/**
 * What m3uedit shows when it is started.
 */
public enum StartupMode {
    /**
     * The start screen with the recently used projects.
     */
    START_SCREEN,
    /**
     * The projects that were open when m3uedit was closed the last time.
     */
    REOPEN_PROJECTS
}
